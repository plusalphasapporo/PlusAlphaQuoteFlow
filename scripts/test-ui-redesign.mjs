import assert from 'node:assert/strict';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const html=fs.readFileSync('index.html','utf8');
const js=fs.readFileSync('ui/workspace-redesign.js','utf8');
const css=fs.readFileSync('ui/workspace-redesign.css','utf8');
assert.ok(html.includes('<link rel="stylesheet" href="./ui/workspace-redesign.css">'),'stylesheet must load');
assert.ok(html.includes('<script src="./ui/workspace-redesign.js" defer></script>'),'UI enhancement must load');
assert.match(js,/function groupNavigation\(/);
assert.match(js,/function enhanceHome\(/);
assert.match(js,/function enhanceTicket\(/);
assert.match(js,/role === 'support_staff'/);
assert.match(js,/MutationObserver\(synchronize\)/);
assert.match(js,/\.append\(button\)/,'original navigational buttons must be moved rather than replaced');
assert.doesNotMatch(js,/\bfetch\s*\(/,'presentation layer must not initiate new data requests');
assert.doesNotMatch(js,/\.innerHTML\s*=\s*html\b/,'avoid wholesale app replacement');
assert.match(css,/@media\(max-width:680px\)/,'mobile breakpoint');
assert.match(css,/\.qf-home-panel\[hidden\]/,'tab hiding mechanism');
assert.match(css,/:focus-visible/,'keyboard focus ring');
assert.match(html,/getAuthenticatorAssuranceLevel/,'existing MFA remains');
assert.match(html,/TeamViewerセッションを発行/,'existing remote operation remains');
assert.match(html,/保存済み検索・Web調査/,'existing AI web research remains');
const checked=spawnSync(process.execPath,['--check','ui/workspace-redesign.js'],{encoding:'utf8'});
assert.equal(checked.status,0,checked.stderr || 'workspace-redesign.js syntax');
console.log('Workspace UI redesign static safety checks passed.');
